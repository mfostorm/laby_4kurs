raw = pd.read_csv(HERE.parent / 'Лаба_4' / 'data' / 'ai4i2020.csv', encoding='utf-8-sig')
SENS = ['Air temperature [K]', 'Process temperature [K]', 'Rotational speed [rpm]',
        'Torque [Nm]', 'Tool wear [min]']
SHORT = {'Air temperature [K]': 'Температура воздуха', 'Process temperature [K]': 'Температура процесса',
         'Rotational speed [rpm]': 'Частота вращения', 'Torque [Nm]': 'Крутящий момент',
         'Tool wear [min]': 'Износ инструмента'}
ac = {c: raw[c].autocorr(1) for c in SENS}
step = {c: raw[c].diff().abs().mean() for c in SENS}
std = {c: raw[c].std() for c in SENS}
power = raw['Torque [Nm]'] * raw['Rotational speed [rpm]'] * 2 * np.pi / 60
d = raw['Tool wear [min]'].diff()
prev = raw['Type'].shift(1).map({'L': 2, 'M': 3, 'H': 5})
wear_ok, wear_n = int((d[d >= 0] == prev[d >= 0]).sum()), int((d >= 0).sum())
resets = int((d < 0).sum())

r = Report()


