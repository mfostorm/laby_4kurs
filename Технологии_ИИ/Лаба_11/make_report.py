"""Отчёт по семантической сети: python network.py && python make_report.py."""
import json
from pathlib import Path
import platform
import sys
import networkx as nx

HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE.parent/'tools'))
from docx_report import Report, num
D=json.loads((HERE/'results'/'analysis.json').read_text(encoding='utf-8'))
S=D['statistics']; Q=D['searches']
r=Report()
r.section('Раздел 1. Цель работы и задачи')
r.p('Лабораторная работа № 11. Построение и анализ семантической сети. '
    'Вариант 10: промышленное оборудование и предиктивное обслуживание.')
r.p('Цель работы - представить связи объектов хранилища в виде семантической сети '
    'NetworkX, вычислить статистики и центральности, найти пути и сообщества, '
    'визуализировать читаемый фрагмент.')
r.items(['определить типы узлов и рёбер на основе данных PostgreSQL;',
         'построить сеть и выполнить статистический анализ;',
         'реализовать три запроса поиска связей;',
         'вычислить топ-5 по четырём центральностям и выделить сообщества;',
         'построить изображение 30–50 узлов с цветами, размерами и подписями.'],numbered=True)
r.section('Раздел 2. Источники и уровень агрегации')
r.p('Основа - хранилище dwh из работ 5–6, а не случайно созданные связи. Выгружены '
    'dim_equipment, dim_tool, dim_quality_class, dim_failure_type, fact_observation '
    'и fact_failure_event. Все SELECT выполняются в одной read-only транзакции '
    'REPEATABLE READ, чтобы агрегаты описывали согласованный снимок.')
r.p(f"Использованы все {num(D['source']['observations'])} наблюдений и "
    f"{D['source']['failure_events']} события отказа. Вместо повторения графа из "
    '21 651 индивида работы 8 построена самостоятельная агрегированная сеть '
    'производственных циклов: 120 циклов, один станок, три класса качества, '
    'шесть типов событий (кроме NONE) и пять рекомендуемых работ.')
r.p('Одна связь PROCESSES суммирует наблюдения пары «цикл–класс», а HAS-FAILURE — '
    'события пары «цикл–тип отказа». Частота хранится в count. Таким образом, данные '
    'не отбрасываются, но отдельные изделия и последовательность наблюдений не являются '
    'узлами этой модели. Сеть подходит для анализа обслуживания по циклам, а не для '
    'изучения временной динамики каждого датчика.')
r.table('Типы узлов, источники и количества',
        ['Тип','Источник в PostgreSQL','Число','Атрибуты'],
        [[x['type'],x['source'],x['count'],
          {'Станок':'name: инвентарный номер',
           'Цикл':'name, products, end_reason',
           'Класс':'name: L/M/H, osf_limit',
           'Отказ':'name: код, description',
           'Работа':'name: текст рекомендации'}[x['type']]] for x in D['node_types']],
        widths=[2,7.5,1.5,5.5],size=11)
r.table('Типы связей, источники и количества',
        ['Тип ребра','Источник / агрегация','Число','Атрибут count'],
        [[x['type'],x['source'],x['count'],
          {'HAS-CYCLE':'Число наблюдений цикла',
           'PROCESSES':'Число изделий класса в цикле',
           'HAS-FAILURE':'Число событий типа в цикле',
           'RECOMMENDS':'1: связь справочника, не частота событий'}[x['type']]]
         for x in D['edge_types']],widths=[3.1,7.6,1.4,4.4],size=10)
r.p('Тип и имя узла задаются через nx.set_node_attributes, тип отношения хранится '
    'в edge_type. Уникальные ключи E/C/Q/F/A с префиксами исключают совпадение '
    'идентификаторов разных сущностей. Одинаковый текст рекомендации дедуплицируется. '
    'Файл results/semantic_network.graphml сохраняет и структуру, и атрибуты.')
r.code('g = nx.DiGraph()\n'
       'g.add_node("C39")\n'
       'nx.set_node_attributes(g, {"C39": {"node_type": "Цикл", "name": "Цикл 39"}})\n'
       'g.add_edge("C39", "F2", edge_type="HAS-FAILURE", count=n_events)\n'
       'u = g.to_undirected()')
r.p('В отличие от OWL-онтологии работы 7, сеть не выполняет логический вывод, '
    'не содержит всех аксиом классов и не проверяет непротиворечивость. Она сохраняет '
    'семантику типизированных отношений как атрибуты графа. Связь с работой 8 '
    'содержательная: те же циклы, классы, типы отказов и рекомендации, но другое зерно.')
r.section('Раздел 3. Статистический анализ')
r.p('Смысл отношений направлен. Статистики компонент, диаметр, расстояния, degree, '
    'betweenness, closeness и Louvain вычислены в простой неориентированной проекции U, '
    'поскольку нужны слабые связи объектов. PageRank вычислен на исходном направленном G. '
    'Метрики точные: приближения по выборке опорных узлов не использовались.')
r.table('Характеристики полной сети',['Характеристика','Значение','Интерпретация'],
        [['Узлы',S['nodes'],'Все агрегированные объекты'],
         ['Рёбра',S['edges'],'Уникальные направленные типизированные отношения'],
         ['Плотность G',num(S['density_directed'],5),'m / (n · (n − 1))'],
         ['Слабые компоненты',S['weak_components'],'Все объекты связаны при игнорировании направления'],
         ['Сильные компоненты',S['strong_components'],'Циклов по направлению отношений нет'],
         ['Диаметр наибольшей компоненты U',S['diameter_largest_undirected'],'Максимальная длина кратчайшего пути'],
         ['Средняя полная степень G',num(S['mean_total_degree'],3),'2m / n, сумма входящей и исходящей'],
         ['Максимальная степень',S['max_degree'],'Станок и все три класса: по 120 циклов'],
         ['Средняя кластеризация U',num(S['clustering_undirected'],3),'В этой схеме отсутствуют треугольники']],
        widths=[6.4,2.2,7.9],size=11)
r.p('Частоты count не трактуются как длины путей: большой объём совместной обработки '
    'не означает большее расстояние. Все алгоритмы запущены без весов. Поэтому '
    'классы L, M и H имеют одинаковую топологическую центральность, хотя число '
    'изделий разных классов различается. Это свойство выбранной модели, а не вывод '
    'об одинаковой частоте производства или риска.')
r.section('Раздел 4. Поиск путей и предметных связей')
r.subsection('4.1. Кратчайший путь')
r.p('Запрос: как класс L связан с проверкой системы охлаждения? '
    'Функция nx.shortest_path(U, "Q1", "A2").')
r.p('Результат: '+' → '.join(Q['shortest']['names'])+
    f". Длина — {Q['shortest']['edges']} ребра. "
    'Путь читается так: в цикле 39 обрабатывались изделия L; в этом цикле '
    'зафиксирован HDF; справочник рекомендует проверку охлаждения. '
    'Первая дуга проходится против направления PROCESSES. Это объясняет '
    'структурную связь, но не доказывает причинность класса L и отказа.')
r.subsection('4.2. Окрестность радиуса 2')
r.p('Запрос: какие объекты находятся не далее двух шагов от HDF? '
    'Функция nx.ego_graph(U, "F2", radius=2).')
r.p(f"Получено {Q['ego']['count']} узла, включая центральный HDF. Полный список "
    'идентификаторов сохранён в analysis.json. Для исходного направленного графа '
    'исходящая окрестность имела бы другой смысл, поэтому проекция U указана явно.')
r.subsection('4.3. Циклы с нарушением теплоотвода')
r.p('Запрос: в каких циклах были события HDF и сколько всего событий? '
    'Использованы G.predecessors("F2") и сумма count по HAS-FAILURE.')
r.p(f"Найдено {Q['hdf_cycles']['count']} циклов: "+
    ', '.join(n[1:] for n in sorted(Q['hdf_cycles']['nodes'],key=lambda x:int(x[1:])))+
    f". Всего {Q['hdf_cycles']['events']} событий HDF. "
    'Это совпадает с метками исходного хранилища и позволяет выбрать '
    'производственные циклы для анализа охлаждения без обхода всех изделий.')
r.section('Раздел 5. Анализ центральности')
r.p('Degree = deg(U)/(n−1). Betweenness — нормированная доля кратчайших путей '
    'между другими узлами через данный узел. Closeness — обратное среднее '
    'расстояние по связной U. PageRank — стационарная важность по направленным '
    'ссылкам (alpha = 0,85, weight = None, tol = 10⁻¹²). Равенства '
    'разрешаются лексикографически по ID для воспроизводимого топ-5.')
r.table('Топ-5 по четырём метрикам',
        ['Метрика','1','2','3','4','5'],
        [[metric]+[name+'\n'+num(value,6) for _,name,value in values]
         for metric,values in D['centrality'].items()],
        widths=[3.1,2.68,2.68,2.68,2.68,2.68],size=10)
r.p('Станок и все три класса связаны со всеми 120 циклами и одинаково лидируют '
    'по трём неориентированным метрикам. Это хабы модели. Среди типов отказов '
    'OSF — наиболее связный: он встречается во многих циклах. PageRank '
    'выделяет классы как узлы, принимающие ссылки из циклов, поэтому его '
    'рейтинг не совпадает с betweenness. Центральность не является вероятностью отказа.')
r.section('Раздел 6. Сообщества')
r.p('Выбран Louvain из NetworkX: последовательное улучшение модулярности '
    'и свёртка найденных сообществ. Использованы U, weight=None, resolution=1, '
    'seed=10. Типовые группы не заданы алгоритму заранее.')
